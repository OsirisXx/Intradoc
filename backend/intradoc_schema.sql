    FOREIGN KEY (ASSIGNED_TO) REFERENCES USER(USER_ID) ON DELETE SET NULL,
    FOREIGN KEY (CREATED_BY) REFERENCES USER(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY (FORWARDED_BY) REFERENCES USER(USER_ID) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- TABLE 10: TASK (must be created before FEEDBACK and SYSTEM_NOTIFICATION)
CREATE TABLE IF NOT EXISTS TASK (
    TASK_ID INT AUTO_INCREMENT PRIMARY KEY,
    TITLE VARCHAR(255) NOT NULL,
    DESCRIPTION TEXT NULL,
    ASSIGNED_TO INT NOT NULL,
    ASSIGNED_BY INT NOT NULL,
    DUE_DATE DATETIME NOT NULL,
    PRIORITY ENUM('low','medium','high','urgent') NULL DEFAULT 'medium',
    STATUS ENUM('pending','in_progress','completed','cancelled') NULL DEFAULT 'pending',
    CATEGORY VARCHAR(100) NULL,
    TAGS TEXT NULL,
    REQUIRES_DOCUMENT TINYINT(1) NULL DEFAULT 0,
    SECTION_ID INT NULL,
    CREATED_AT DATETIME NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    LINKED_DOCUMENT_ID INT NULL,
    FOREIGN KEY (ASSIGNED_TO) REFERENCES USER(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY (ASSIGNED_BY) REFERENCES USER(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY (SECTION_ID) REFERENCES SECTION(SECTION_ID) ON DELETE SET NULL,
    FOREIGN KEY (LINKED_DOCUMENT_ID) REFERENCES DOCUMENT(DOCUMENT_ID) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

