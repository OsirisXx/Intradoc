CREATE TABLE IF NOT EXISTS USER (
    USER_ID INT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(255) NOT NULL,
    ID_NUMBER VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    PROFILE_IMAGE VARCHAR(500) NULL,
    SECTION_ID INT NOT NULL,
    FUNCTIONAL_ROLE ENUM('staff','section_unit_head','division_manager','regional_director','admin') NOT NULL DEFAULT 'staff',
    ORGANIZATIONAL_ROLE VARCHAR(100) NULL,
    STATUS ENUM('active','pending','suspended','inactive') NULL DEFAULT 'active',
    CREATED_AT TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    APPROVED_AT TIMESTAMP NULL,
    APPROVED_BY INT NULL,
    FOREIGN KEY (SECTION_ID) REFERENCES SECTION(SECTION_ID) ON DELETE CASCADE,
    FOREIGN KEY (APPROVED_BY) REFERENCES USER(USER_ID) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

